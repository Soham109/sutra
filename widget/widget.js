  function jsonLdBlocks(doc, warnings) {
    var out = []
    var scripts = qsa(doc, 'script')
    for (var i = 0; i < scripts.length; i++) {
      var type = (attr(scripts[i], 'type') || '').toLowerCase()
      if (type.indexOf('ld+json') === -1) continue
      var raw = (scripts[i].textContent || '').trim()
      if (!raw) continue
      raw = raw
        .replace(/^<!--/, '').replace(/-->$/, '')
        .replace(/^\s*\/\*\s*<!\[CDATA\[\s*\*\//, '')
        .replace(/\/\*\s*\]\]>\s*\*\/\s*$/, '')
        .trim()
      var parsed = tryJson(raw)
      if (parsed === undefined) parsed = tryJson(raw.replace(/,\s*([}\]])/g, '$1'))
      if (parsed === undefined) {
        // Some CMSes emit several top-level objects back to back.
        var chunks = raw.split(/}\s*{/)
        if (chunks.length > 1) {
          for (var c = 0; c < chunks.length; c++) {
            var piece = (c === 0 ? '' : '{') + chunks[c] + (c === chunks.length - 1 ? '' : '}')
            var p = tryJson(piece)
            if (p !== undefined) out.push(p)
          }
          continue
        }
        if (warnings) warnings.push('a JSON-LD block on this page did not parse')
        continue
      }
      out.push(parsed)
    }
    return out
  }
  function tryJson(s) {
    try {
      return JSON.parse(s)
    } catch (e) {
      return undefined
    }
  }

  function collect(value, want, acc, depth) {
    acc = acc || []
    depth = depth || 0
    if (depth > 12 || acc.length > 400) return acc
    if (Array.isArray(value)) {
      for (var i = 0; i < value.length; i++) collect(value[i], want, acc, depth + 1)
      return acc
    }
    if (!value || typeof value !== 'object') return acc
    var types = typesOf(value)
    for (var t = 0; t < types.length; t++) {
      if (want.indexOf(types[t]) !== -1) {
        acc.push(value)
        break
      }
    }
    for (var k = 0; k < RECURSE_KEYS.length; k++) {
      var key = RECURSE_KEYS[k]
      if (value[key]) collect(value[key], want, acc, depth + 1)
    }
    return acc
  }

  /** Offer | AggregateOffer | PriceSpecification | array -> price candidate. */
  function offerPrice(offers, fallbackCurrency, warnings) {
    if (!offers) return null
    if (Array.isArray(offers)) {
      var best = null
      for (var i = 0; i < offers.length; i++) {
        var p = offerPrice(offers[i], fallbackCurrency, warnings)
        if (p && (!best || p.amount_minor < best.amount_minor)) best = p
      }
      return best
    }
    if (typeof offers !== 'object') return null
    var cur =
      firstString(offers.priceCurrency) ||
      firstString(offers.priceSpecification && offers.priceSpecification.priceCurrency) ||
      fallbackCurrency
    var types = typesOf(offers)

    var raw = offers.price
    if (raw === undefined || raw === null || raw === '') {
      if (offers.priceSpecification) {
        var ps = Array.isArray(offers.priceSpecification) ? offers.priceSpecification[0] : offers.priceSpecification
        if (ps) {
          raw = ps.price
          cur = firstString(ps.priceCurrency) || cur
        }
      }
    }
    if ((raw === undefined || raw === null || raw === '') && offers.lowPrice !== undefined) {
      raw = offers.lowPrice
      if (warnings && types.indexOf('AggregateOffer') !== -1) {
        warnings.push('this page lists a price range — used the lowest (' + firstString(offers.lowPrice) + ')')
      }
    }
    if (raw === undefined || raw === null || raw === '') {
      // Offer wrapping another Offer / itemOffered with its own offers.
      if (offers.offers) return offerPrice(offers.offers, cur, warnings)
      if (offers.itemOffered && offers.itemOffered.offers) return offerPrice(offers.itemOffered.offers, cur, warnings)
      return null
    }
    var m = parseMoney(raw, cur, { structured: true })
    if (!m) return null
    if (m.amount_minor <= 0) return null
    return m
  }

  function nodeUrl(node) {
    return firstString(node.url) || firstString(node['@id']) || null
  }

  /** Prefer the node that is actually about *this* URL. */
  function pickForPage(nodes, loc) {
    if (nodes.length <= 1) return { node: nodes[0] || null, ambiguous: false }
    var href = ''
    var path = ''
    try {
      href = String(loc.href || '').split('#')[0]
      path = String(loc.pathname || '')
    } catch (e) {}
    for (var i = 0; i < nodes.length; i++) {
      var u = nodeUrl(nodes[i])
      if (!u) continue
      var normalized = u.split('#')[0].split('?')[0]
      if (href && (normalized === href.split('?')[0] || href.indexOf(normalized) === 0)) {
        return { node: nodes[i], ambiguous: false }
      }
      if (path && path.length > 1 && normalized.slice(-path.length) === path) {
        return { node: nodes[i], ambiguous: false }
      }
    }
    return { node: nodes[0], ambiguous: true }
  }

  function fromJsonLd(doc, loc, ctx) {
    var warnings = []
    var docs = jsonLdBlocks(doc, warnings)
    if (!docs.length) return null

    var orders = collect(docs, ORDER_TYPES)
    var products = collect(docs, PRODUCT_TYPES)
    var events = collect(docs, EVENT_TYPES)
    var offers = collect(docs, OFFER_TYPES)
    if (!orders.length && !products.length && !events.length && !offers.length) return null

    var cand = { source: 'json-ld', warnings: warnings, items: [], fees: [] }
    var fallbackCur = ctx.weakCurrency

    // -- Order: the strongest signal there is. A real basket.
    if (orders.length) {
      var order = orders[0]
      var lines = order.orderedItem
        ? Array.isArray(order.orderedItem) ? order.orderedItem : [order.orderedItem]
        : []
      var orderCur =
        firstString(order.priceCurrency) ||
        firstString(order.totalPaymentDue && order.totalPaymentDue.priceCurrency) ||
        fallbackCur
      for (var i = 0; i < lines.length; i++) {
        var line = lines[i]
        var prod = line.orderedItem || line.itemOffered || line
        var lp = offerPrice(line.acceptedOffer || prod.offers, orderCur, warnings)
        var qty = Number(firstString(line.orderQuantity) || firstString(line.eligibleQuantity) || 1) || 1
        if (lp) {
          cand.items.push({
            name: firstString(prod.name) || firstString(line.name) || 'Item ' + (i + 1),
            unit_amount: lp.amount_minor,
            qty: Math.max(1, Math.round(qty)),
            sku: firstString(prod.sku) || firstString(prod.productID) || null,
          })
          orderCur = lp.currency
        }
      }
      var due = order.totalPaymentDue
      var total = due ? parseMoney(firstString(due.price) || due.price, firstString(due.priceCurrency) || orderCur, { structured: true }) : null
      cand.title = firstString(order.name) || (order.orderNumber ? 'Order ' + firstString(order.orderNumber) : null)
      cand.currency = (total && total.currency) || orderCur
      cand.total_minor = total ? total.amount_minor : null
      cand.merchantName = firstString(order.seller) || firstString(order.merchant) || firstString(order.broker)
      cand.kind = 'order'
      cand.confidence = 0.95
      if (cand.items.length || cand.total_minor) return cand
    }

    // -- Event (a showing, a gig, a screening) — the ticket case.
    var chosen = null
    var kind = null
    var ambiguous = false
    var siblings = 0
    if (events.length) {
      var pe = pickForPage(events, loc)
      chosen = pe.node
      ambiguous = pe.ambiguous
      siblings = events.length
      kind = 'event'
      if (events.length > 3 && ambiguous) {
        warnings.push('this page describes ' + events.length + ' events — picked the first one')
      }
    }
    if (!chosen && products.length) {
      var pp = pickForPage(products, loc)
      chosen = pp.node
      ambiguous = pp.ambiguous
      siblings = products.length
      kind = 'product'
      if (products.length > 3 && ambiguous) {
        warnings.push('this page describes ' + products.length + ' products — picked the first one')
      }
    }
    if (!chosen && offers.length) {
      chosen = offers[0]
      kind = 'offer'
    }
    if (!chosen) return null

    var price = null
    if (kind === 'offer') {
      price = offerPrice(chosen, fallbackCur, warnings)
    } else {
      price = offerPrice(chosen.offers, fallbackCur, warnings)
      if (!price && chosen.hasVariant) price = offerPrice(collect(chosen.hasVariant, PRODUCT_TYPES).map(function (v) { return v.offers }), fallbackCur, warnings)
      if (!price && chosen.albumRelease) price = offerPrice(collect(chosen.albumRelease, ['MusicRelease', 'Product']).map(function (v) { return v.offers }), fallbackCur, warnings)
      if (!price && offers.length) price = offerPrice(offers[0], fallbackCur, warnings)
    }

    cand.kind = kind
    cand.title = firstString(chosen.name) || firstString(chosen.headline) || null
    cand.image = firstString(chosen.image) || null
    cand.merchantName =
      firstString(chosen.seller) ||
      firstString(chosen.organizer) ||
      firstString(chosen.brand) ||
      firstString(chosen.offers && chosen.offers.seller) ||
      null

    if (kind === 'event') {
      var place = chosen.location
      if (Array.isArray(place)) place = place[0]
      cand.event = {
        start: firstString(chosen.startDate) || null,
        end: firstString(chosen.endDate) || null,
        venue: place ? firstString(place.name) || firstString(place.address) : null,
        address: place && place.address ? addressLine(place.address) : null,
      }
    }

    if (price) {
      cand.currency = price.currency
      cand.items.push({
        name: cand.title || (kind === 'event' ? 'Ticket' : 'Item'),
        unit_amount: price.amount_minor,
        qty: 1,
        sku: firstString(chosen.sku) || firstString(chosen.productID) || firstString(chosen.mpn) || null,
      })
      cand.total_minor = price.amount_minor
      cand.confidence = kind === 'offer' ? 0.82 : 0.9
      // Nothing on the page said which of these the page is *about*. On a
      // search results page that is a coin flip, not a detection.
      //
      // The penalty scales with how many things we were choosing between: a
      // real 309-listing Craigslist page was landing on 0.6 and being labelled
      // "good confidence", which is a coin flip wearing a reassuring word. Two
      // candidates is a mild doubt; three hundred is not a detection at all.
      if (ambiguous) {
        var spread = Math.min(0.45, 0.12 + 0.13 * Math.log2(Math.max(2, siblings)))
        cand.confidence -= spread
      }
    } else {
      // Name but no price is still worth having — og/DOM may fill the number.
      cand.confidence = 0.4
      warnings.push('structured data named the item but carried no price')
    }
    return cand
  }

  function addressLine(a) {
    if (!a) return null
    if (typeof a === 'string') return clean(a)
    var parts = [a.streetAddress, a.addressLocality, a.addressRegion, a.postalCode, a.addressCountry]
      .map(firstString)
      .filter(Boolean)
    return parts.length ? clean(parts.join(', ')) : null
  }

