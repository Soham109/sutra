  /**
   * Turn a digit-group string into a Number, deciding which separator is the
   * decimal mark. Handles US (1,234.56), European (1.234,56), Indian lakh
   * grouping (1,23,456), space grouping (1 234,56) and bare integers.
   */
  function parseGrouped(numeric) {
    numeric = numeric.replace(/[   \s'’]/g, '')
    if (!/\d/.test(numeric)) return null
    var neg = /^-/.test(numeric)
    numeric = numeric.replace(/-/g, '')

    var lastDot = numeric.lastIndexOf('.')
    var lastComma = numeric.lastIndexOf(',')
    var out
    if (lastDot === -1 && lastComma === -1) {
      out = numeric
    } else {
      var decIdx = Math.max(lastDot, lastComma)
      var decimals = numeric.length - decIdx - 1
      var bothKinds = lastDot !== -1 && lastComma !== -1
      // 1–2 digits after the final separator => it's the decimal mark.
      // Exactly 3 digits => a thousands mark (1,234 / 1.234 / 1,23,456),
      // unless it's the *only* separator and the other kind appears earlier.
      if (decimals >= 1 && decimals <= 2) {
        out = numeric.slice(0, decIdx).replace(/[.,]/g, '') + '.' + numeric.slice(decIdx + 1)
      } else if (decimals === 3 || bothKinds) {
        out = numeric.replace(/[.,]/g, '')
      } else {
        // 4+ digits after a separator is not a grouping and not a sane
        // currency decimal — refuse rather than invent a number.
        return null
      }
    }
    var v = Number(out)
    if (!isFinite(v)) return null
    return neg ? -v : v
  }

  /**
   * parseMoney('$1,234.56')        -> { amount_minor: 123456, currency: 'USD' }
   * parseMoney('₹1,23,456','INR')  -> { amount_minor: 12345600, currency: 'INR' }
   * parseMoney('1.234,56 €')       -> { amount_minor: 123456, currency: 'EUR' }
   * parseMoney(45)                 -> { amount_minor: 4500, currency: fallback }
   *
   * opts.structured: the value came from a machine-readable field (JSON-LD,
   * microdata, meta), where a bare `1.234` means one-point-two-three-four and
   * not one thousand. Grouping heuristics only kick in if it isn't a clean
   * decimal literal.
   */
  function parseMoney(raw, fallbackCurrency, opts) {
    opts = opts || {}
    if (raw === null || raw === undefined || raw === '') return null
    if (typeof raw === 'number') {
      if (!isFinite(raw)) return null
      return toMinor(raw, fallbackCurrency || 'USD')
    }
    var s = String(raw).trim()
    if (!s) return null
    if (/^(free|gratis|n\/?a|tbd|price on request)$/i.test(s)) return null

    var currency = currencyFromString(s) || fallbackCurrency || null

    var value
    if (opts.structured && /^-?\d+(\.\d+)?$/.test(s)) {
      value = Number(s)
    } else {
      var numeric = s.replace(/[^\d.,\-    ]/g, '')
      value = parseGrouped(numeric)
      if (value === null && opts.structured) {
        var plain = /-?\d+(?:\.\d+)?/.exec(s)
        value = plain ? Number(plain[0]) : null
      }
    }
    if (value === null || value === undefined || !isFinite(value)) return null
    return toMinor(value, currency || 'USD', currency === null)
  }

  function toMinor(value, currency, currencyGuessed) {
    var c = String(currency).toUpperCase()
    return {
      amount_minor: Math.round(value * minorUnits(c)),
      currency: c,
      currency_guessed: !!currencyGuessed,
    }
  }

  // A money-shaped run of text: symbol-then-number, or number-then-code.
  // A currency marker is mandatory — a bare number is never money here.
