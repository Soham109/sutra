  function syncCandidates(doc, loc, ctx) {
    var out = []
    out.push(guard(fromSelection, doc, loc, ctx))
    out.push(guard(fromJsonLd, doc, loc, ctx))
    out.push(guard(fromMicrodata, doc, loc, ctx))
    out.push(guard(fromMeta, doc, loc, ctx))
    if (ctx.shopify !== false && isShopify(doc, ctx.win)) out.push(guard(fromShopifyMeta, doc, loc, ctx))
    out = out.filter(Boolean)

    // Scraping the DOM for a total is the last resort in every sense: it is
    // the slowest pass and the only one that can be confidently wrong. Skip it
    // outright when something machine-readable already produced a number.
    var haveGoodNumber = false
    for (var i = 0; i < out.length; i++) {
      if (out[i].total_minor !== null && out[i].total_minor !== undefined && (out[i].confidence || 0) >= 0.66) {
        haveGoodNumber = true
        break
      }
    }
    if (!haveGoodNumber) {
      var dom = guard(fromDomTotal, doc, loc, ctx)
      if (dom) out.push(dom)
      // Last of the last resorts. A product page has no "Total" label to
      // anchor on — it has a price and an "Add to Cart" button — so when
      // nothing above found a number at all, try the price beside that button.
      // This is the only strategy that reaches a marketplace which renders its
      // price in JavaScript, and only from inside a real browser.
      if (!dom || dom.total_minor === null || dom.total_minor === undefined) {
        var buy = guard(fromBuyAction, doc, loc, ctx)
        if (buy) out.push(buy)
      }
    }
    return out
  }

  function guard(fn, doc, loc, ctx) {
    try {
      return fn(doc, loc, ctx)
    } catch (e) {
      return null
    }
  }

  /** Everything except the network. Safe to call anywhere, never rejects. */
  function detectCartSync(doc, loc, opts) {
    doc = doc || (typeof document !== 'undefined' ? document : null)
    loc = loc || (typeof location !== 'undefined' ? location : {})
    if (!doc) return merge([], { title: '', querySelector: function () { return null }, querySelectorAll: function () { return [] } }, loc, makeCtx({ querySelector: function () { return null }, querySelectorAll: function () { return [] } }, loc, opts))
    var ctx = makeCtx(doc, loc, opts)
    return merge(syncCandidates(doc, loc, ctx), doc, loc, ctx)
  }

  /** The full thing, including Shopify's /cart.js. Always resolves. */
  function detectCart(doc, loc, opts) {
    doc = doc || (typeof document !== 'undefined' ? document : null)
    loc = loc || (typeof location !== 'undefined' ? location : {})
    if (!doc) return Promise.resolve(detectCartSync(doc, loc, opts))
    var ctx
    try {
      ctx = makeCtx(doc, loc, opts)
    } catch (e) {
      return Promise.resolve(detectCartSync(doc, loc, opts))
    }
    var sync = syncCandidates(doc, loc, ctx)
    var wantCart = ctx.shopify !== false && isShopify(doc, ctx.win)
    var cartP = wantCart ? guardP(fromShopifyCart, doc, loc, ctx) : Promise.resolve(null)
    return cartP.then(function (cart) {
      return merge(cart ? [cart].concat(sync) : sync, doc, loc, ctx)
    }).catch(function () {
      return merge(sync, doc, loc, ctx)
    })
  }

  function guardP(fn, doc, loc, ctx) {
    try {
      return Promise.resolve(fn(doc, loc, ctx)).catch(function () { return null })
    } catch (e) {
      return Promise.resolve(null)
    }
  }

