  var TOTAL_LABELS = [
    [/\bgrand\s*total\b/i, 100],
    [/\border\s*total\b/i, 96],
    [/\btotal\s*(?:amount\s*)?due\b/i, 94],
    [/\bamount\s*due\b/i, 92],
    [/\bamount\s*payable\b/i, 90],
    [/\btotal\s*payable\b/i, 90],
    [/\bestimated\s*total\b/i, 84],
    [/\btotal\s*price\b/i, 80],
    [/\btotal\s*cost\b/i, 78],
    [/\byou\s*pay\b/i, 76],
    [/\bto\s*pay\b/i, 74],
    [/\bcart\s*total\b/i, 88],
    [/\btotal\b/i, 60],
    [/\bpayable\b/i, 58],
    [/\bsub\s*-?\s*total\b/i, 30],
  ]
  var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, TEMPLATE: 1, SVG: 1, HEAD: 1, IFRAME: 1, CANVAS: 1, SELECT: 1 }

  function countWords(s) {
    var m = String(s).trim().match(/[^\s]+/g)
    return m ? m.length : 0
  }

  /** Best-scoring total label in `s`, with where it sits. */
  function labelHit(s) {
    var best = null
    for (var i = 0; i < TOTAL_LABELS.length; i++) {
      TOTAL_LABELS[i][0].lastIndex = 0
      var m = TOTAL_LABELS[i][0].exec(s)
      if (!m) continue
      var score = TOTAL_LABELS[i][1]
      // Sub-total must never be scored as "total".
      if (/\btotal\b/i.test(m[0]) && /\bsub\s*-?\s*total\b/i.test(s) && score > 30) {
        var subIdx = s.search(/\bsub\s*-?\s*total\b/i)
        if (subIdx !== -1 && Math.abs(subIdx - m.index) < 12) score = 30
      }
      if (!best || score > best.score) best = { score: score, index: m.index, length: m[0].length }
    }
    return best
  }

  function isHidden(el) {
    try {
      if (el.hasAttribute && (el.hasAttribute('hidden') || el.getAttribute('aria-hidden') === 'true')) return true
      var st = el.getAttribute && el.getAttribute('style')
      if (st && /display\s*:\s*none|visibility\s*:\s*hidden/i.test(st)) return true
    } catch (e) {}
    return false
  }

  /** Depth-first text-node walk that respects SKIP_TAGS and hidden nodes. */
  function walkText(root, visit, budget) {
    var stack = [root]
    var seen = 0
    while (stack.length) {
      var n = stack.pop()
      if (!n) continue
      if (n.nodeType === 3) {
        var t = n.nodeValue
        if (t && t.trim()) {
          if (++seen > (budget || 12000)) return
          visit(n, t)
        }
        continue
      }
      if (n.nodeType !== 1) continue
      if (SKIP_TAGS[n.tagName]) continue
      if (isHidden(n)) continue
      var kids = n.childNodes
      for (var i = kids.length - 1; i >= 0; i--) stack.push(kids[i])
    }
  }

  function rowFor(node) {
    var el = node.parentElement
    var hops = 0
    var best = el
    while (el && hops < 5) {
      var tag = el.tagName
      var cls = (attr(el, 'class') || '').toLowerCase()
      if (tag === 'TR' || tag === 'LI' || tag === 'DL' ||
          /(^|[\s_-])(total|summary|order[-_]?total|grand|amount|price|row|line)([\s_-]|$)/.test(cls)) {
        return el
      }
      best = el
      el = el.parentElement
      hops++
    }
    return best
  }

  /**
   * The price next to the buy button.
   *
   * `fromDomTotal` anchors on words like "Total" and "Amount due", which only
   * exist on a CHECKOUT. A product page has no total — it has a price and a
   * button that says "Add to Cart". So on Amazon, and on every other store
   * whose price is rendered by JavaScript rather than published as markup,
   * every other strategy returns nothing and this one is the only thing left.
   *
   * Deliberately generic rather than a per-site adapter: the anchor is the buy
   * ACTION, which every product page on the internet has, in whatever markup
   * its authors felt like. Confidence stays low and the warning always names
   * the button it anchored on, because this is a read off rendered text, not a
   * fact the merchant published.
   *
   * Only useful in a real browser — running against fetched HTML, the price is
   * usually still an empty div waiting for JavaScript. That is exactly why the
   * extension can do this and pasting a link cannot.
   */
  var BUY_LABELS = /\b(?:add to (?:cart|bag|basket)|buy (?:it )?now|add to trolley|proceed to (?:buy|checkout)|pre-?order now)\b/i

  /**
   * Text that marks a nearby amount as something OTHER than what you would
   * pay: the crossed-out original, the discount, the free-shipping threshold.
   * On a discounted product the list price is the biggest number on the page,
   * so without this the group gets billed the pre-sale price.
   */
  var NOT_THE_PRICE =
    /(?:\blist\s*price\b|\bwas\b|\brrp\b|\bmrp\b|m\.r\.p|\borig(?:inal)?\b|\byou\s*save\b|\bsave\b|\bsavings?\b|\bdiscount\b|\btypical\s*price\b|\bcompare\s*at\b|\bfree\s*(?:shipping|delivery)\b|\borders?\s*over\b|\bspend\b|\bpayments?\s*of\b|\bmonthly\b|\bemi\b|\bper\s*month\b|\/\s*mo\b|\binstal?ments?\b|\bfrom\s*$)/i

  function fromBuyAction(doc, loc, ctx) {
    var body = doc.body
    if (!body) return null
    var buttons = qsa(body, 'button, input[type=submit], a[role=button], [data-action], .a-button-input')
    var anchor = null
    for (var i = 0; i < buttons.length && i < 400; i++) {
      var label = text(buttons[i], 60) || attr(buttons[i], 'value') || attr(buttons[i], 'aria-label') || ''
      if (BUY_LABELS.test(label)) { anchor = { el: buttons[i], label: label.trim() }; break }
    }
    if (!anchor) return null

    // Climb from the button until the surrounding block contains money, but
    // not so far that the whole page counts as "near the button".
    var el = anchor.el
    var hops = 0
    while (el && hops < 7) {
      var blob = text(el, 1200)
      var found = findMoney(blob, ctx.weakCurrency)
      if (found.length) {
        // Drop the amounts that are explicitly NOT what you would pay. A
        // struck-through list price is usually the largest number on a
        // product page, so picking "the biggest one near the button" would
        // reliably overcharge the group on anything discounted.
        var live = []
        for (var f = 0; f < found.length; f++) {
          // The window has to stop at the previous amount. Running a flat 44
          // characters back made "M.R.P: ₹34,990  ₹24,990" reject the sale
          // price too, because the previous label was still inside the window
          // — leaving only the instalment line as a candidate.
          var floor = f > 0 ? found[f - 1].index + found[f - 1].raw.length : 0
          var around = blob.slice(Math.max(floor, found[f].index - 44), found[f].index)
          if (NOT_THE_PRICE.test(around)) continue
          live.push(found[f])
        }
        if (!live.length) { el = el.parentElement; hops++; continue }

        // Of what remains, the one physically nearest the button. Instalment
        // lines ("4 payments of $27.50") and shipping thresholds sit further
        // out; the price sits against the button.
        var best = live[0]
        for (var g = 1; g < live.length; g++) {
          if (live[g].index < best.index) best = live[g]
        }
        if (best.money.amount_minor <= 0) return null
        var name = clean(doc.title) || meta(doc, ['og:title']) || 'Item'
        return {
          source: 'buy-action',
          kind: 'dom',
          title: name,
          currency: best.money.currency,
          total_minor: best.money.amount_minor,
          items: [{ name: name, unit_amount: best.money.amount_minor, qty: 1, sku: null }],
          fees: [],
          confidence: found.length > 6 ? 0.28 : 0.36,
          warnings: [
            'this page publishes no machine-readable price, so this was read off the text beside the "' +
              anchor.label.slice(0, 28) +
              '" button — check it before you split',
          ],
          label: anchor.label.slice(0, 40),
        }
      }
      el = el.parentElement
      hops++
    }
    return null
  }

  function fromDomTotal(doc, loc, ctx) {
    var body = doc.body
    if (!body) return null
    var candidates = []
    var fallbackCur = ctx.weakCurrency

    walkText(body, function (node, raw) {
      var s = raw.replace(/\s+/g, ' ').trim()
      if (s.length > 300) return
      var hit = labelHit(s)
      if (!hit) return
      var score = hit.score

      // Prose guards. "…the total operating revenue was $1.7 billion…" is a
      // sentence, not a checkout line. A total label sits in a short cell,
      // near the front of it, with its number right next to it.
      if (countWords(s) > 12) return
      if (countWords(s.slice(0, hit.index)) > 4) return

      // 1. money in the same text node, right after the label
      var here = findMoney(s, fallbackCur)
      if (here.length) {
        var after = null
        for (var h = 0; h < here.length; h++) {
          if (here[h].index >= hit.index) { after = here[h]; break }
        }
        if (!after) return
        if (after.index - (hit.index + hit.length) > 40) return
        candidates.push({ score: score + 6, money: here[here.length - 1].money, why: s.slice(0, 80), distance: 0 })
        return
      }
      // 2. money in the enclosing row / summary line
      var row = rowFor(node)
      if (!row) return
      var rowText = text(row, 600)
      if (!rowText) return
      // A huge container means we would be grabbing an unrelated number.
      if (rowText.length > 220 || countWords(rowText) > 24) return
      var found = findMoney(rowText, fallbackCur)
      if (!found.length) return
      candidates.push({
        score: score - 4,
        money: found[found.length - 1].money,
        why: rowText.slice(0, 90),
        distance: rowText.length,
      })
    })

    if (!candidates.length) return null
    candidates.sort(function (a, b) {
      if (b.score !== a.score) return b.score - a.score
      return a.distance - b.distance
    })
    var top = candidates[0]
    if (top.score < 55) return null // subtotal-only pages: not good enough

    var conf = top.score >= 90 ? 0.45 : top.score >= 74 ? 0.38 : 0.3
    var warnings = ['this number was read off the page text ("' + top.why.trim() + '") — check it before you split']
    // Several different totals on one page is a red flag.
    var distinct = {}
    for (var i = 0; i < candidates.length && i < 12; i++) distinct[candidates[i].money.amount_minor] = 1
    var n = 0
    for (var k in distinct) if (Object.prototype.hasOwnProperty.call(distinct, k)) n++
    if (n > 3) {
      conf -= 0.08
      warnings.push('found ' + n + ' different total-ish amounts on this page')
    }

    var title = clean(doc.title) || meta(doc, ['og:title']) || 'Order'
    return {
      source: 'dom-total',
      kind: 'dom',
      title: title,
      currency: top.money.currency,
      total_minor: top.money.amount_minor,
      items: [{ name: null, unit_amount: top.money.amount_minor, qty: 1, sku: null }],
      fees: [],
      confidence: Math.max(0.18, conf),
      warnings: warnings,
      label: top.why.trim(),
    }
  }

