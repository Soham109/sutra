  function createGroup(engine, token, o) {
    var quorum = Math.max(1, Math.ceil(o.members.length * 0.6))
    var policy =
      o.policy === 'quorum' ? { type: 'quorum', m: quorum }
        : o.policy === 'deadline'
          ? {
              type: 'deadline',
              at: new Date(Date.now() + o.deadline * 60000).toISOString(),
              primary: { type: 'all_of' },
              fallback: { type: 'quorum', m: quorum },
            }
          : { type: 'all_of' }

    var body = {
      title: o.title,
      merchant: {
        id: 'widget',
        name: o.merchantName.slice(0, 80),
        url: /^https?:\/\//.test(o.merchantUrl) ? o.merchantUrl : 'https://' + location.hostname,
        country_code_iso2: (navigator.language || 'en-US').split('-')[1] || 'US',
      },
      cart: {
        items: [{
          sku: 'sutra-widget-1',
          name: o.itemName || 'Item',
          unit_amount: o.unit_amount,
          qty: o.qty,
          claimants: ['mi_all'],
        }],
        fees: (o.fees || []).slice(0, 8).map(function (f, i) {
          return { name: String(f.name || 'Fee ' + (i + 1)).slice(0, 60), amount: Math.max(0, Math.round(f.amount || 0)) }
        }),
        currency: o.currency,
      },
      members: o.members.slice(0, 20).map(function (n) { return { name: n.slice(0, 60), role: 'payer' } }),
      policy: policy,
      deadline_minutes: Math.min(10080, o.deadline),
    }

    return fetch(engine + '/v1/groups', {
      method: 'POST',
      headers: { 'content-type': 'application/json', authorization: 'Bearer ' + (token || 'dev-token') },
      body: JSON.stringify(body),
    }).then(function (res) {
      return res.text().then(function (raw) {
        if (!res.ok) {
          var msg = raw
          try { msg = JSON.parse(raw).error || raw } catch (e) {}
          if (res.status === 401) msg = 'The engine rejected the token. Open “Policy, deadline, connection” and paste a valid API token.'
          throw new Error('Engine said ' + res.status + ': ' + String(msg).slice(0, 200))
        }
        return JSON.parse(raw)
      })
    })
  }

