  function fromMeta(doc, loc, ctx) {
    var warnings = []
    var title =
      meta(doc, ['og:title', 'twitter:title']) ||
      clean(doc.title) ||
      (doc.querySelector('h1') ? text(doc.querySelector('h1'), 140) : null)
    var image = meta(doc, ['og:image:secure_url', 'og:image', 'twitter:image', 'twitter:image:src'])
    var site = meta(doc, ['og:site_name', 'application-name'])

    var amount = meta(doc, [
      'product:price:amount', 'og:price:amount', 'product:sale_price:amount',
      'twitter:data1', 'price',
    ])
    var currency = meta(doc, [
      'product:price:currency', 'og:price:currency', 'product:sale_price:currency', 'priceCurrency',
    ])

    // twitter:data1 is a free-form slot — eventbrite puts the *address* in it.
    // Only trust it if its label says price, or the value is unmistakably money.
    var fromData1 = amount !== null && amount === meta(doc, ['twitter:data1'])
    if (fromData1) {
      var label = meta(doc, ['twitter:label1']) || ''
      var looksLikeMoney = !!currencyFromString(amount) && /\d/.test(amount)
      if (!/price|cost|from|amount|fee|ticket/i.test(label) && !looksLikeMoney) amount = null
      else if (looksLikeMoney && !/price|cost|from|amount|fee|ticket/i.test(label)) {
        warnings.push('price came from twitter:data1, which merchants use for anything')
      }
    }

    var money = amount ? parseMoney(amount, currency || ctx.weakCurrency, { structured: true }) : null
    if (money && money.amount_minor <= 0) money = null

    if (!title && !money) return null
    return {
      source: 'og',
      kind: 'product',
      title: title,
      image: image,
      merchantName: site,
      currency: money ? money.currency : currency || null,
      total_minor: money ? money.amount_minor : null,
      items: money ? [{ name: title || 'Item', unit_amount: money.amount_minor, qty: 1, sku: null }] : [],
      fees: [],
      confidence: money ? 0.66 : 0.2,
      warnings: warnings,
    }
  }

