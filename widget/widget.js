  /** Every money-looking substring of `text`, left to right. */
  function findMoney(text, fallbackCurrency) {
    var out = []
    if (!text) return out
    MONEY_RE.lastIndex = 0
    var m
    while ((m = MONEY_RE.exec(text))) {
      var raw = m[0]
      // "$5 off 20% today" — a trailing % means it was never an amount.
      if (text.charAt(m.index + raw.length) === '%') continue
      var money = parseMoney(raw, fallbackCurrency)
      if (!money) continue
      if (money.amount_minor <= 0) continue
      if (money.amount_minor > 1e13) continue
      out.push({ raw: raw.trim(), index: m.index, money: money })
      if (out.length > 200) break
    }
    return out
  }

