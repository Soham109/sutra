  /** Read itemprops belonging to `scope`, not to any nested itemscope. */
  function scopedProp(scope, prop) {
    var all = qsa(scope, '[itemprop~="' + prop + '"]')
    for (var i = 0; i < all.length; i++) {
      var el = all[i]
      var owner = el.parentElement
      var mine = true
      while (owner && owner !== scope) {
        if (owner.hasAttribute && owner.hasAttribute('itemscope')) { mine = false; break }
        owner = owner.parentElement
      }
      if (!mine) continue
      var v =
        attr(el, 'content') ||
        attr(el, 'datetime') ||
        (el.tagName === 'META' ? null : attr(el, 'href') || attr(el, 'src')) ||
        text(el, 300)
      if (v) return v
    }
    return null
  }

  function fromMicrodata(doc, loc, ctx) {
    var scopes = qsa(
      doc,
      '[itemscope][itemtype*="schema.org/Product"],[itemscope][itemtype*="schema.org/Event"],' +
      '[itemscope][itemtype*="schema.org/Offer"],[itemscope][itemtype*="schema.org/Order"]',
    )
    if (!scopes.length) return null
    var warnings = []
    for (var i = 0; i < scopes.length && i < 8; i++) {
      var scope = scopes[i]
      var name = scopedProp(scope, 'name')
      var priceRaw = scopedProp(scope, 'price') || scopedProp(scope, 'lowPrice')
      var cur = scopedProp(scope, 'priceCurrency')
      if (!priceRaw) {
        var nested = qsa(scope, '[itemprop~="offers"]')[0]
        if (nested) {
          priceRaw = scopedProp(nested, 'price') || scopedProp(nested, 'lowPrice')
          cur = cur || scopedProp(nested, 'priceCurrency')
        }
      }
      if (!priceRaw && !name) continue
      var money = priceRaw ? parseMoney(priceRaw, cur || ctx.weakCurrency, { structured: true }) : null
      if (!money && !name) continue
      var avail = scopedProp(scope, 'availability')
      if (avail && /OutOfStock|SoldOut|Discontinued/i.test(avail)) warnings.push('microdata says this item is out of stock')
      return {
        source: 'microdata',
        kind: 'product',
        title: name,
        image: scopedProp(scope, 'image'),
        currency: money ? money.currency : cur || null,
        total_minor: money ? money.amount_minor : null,
        items: money
          ? [{ name: name || 'Item', unit_amount: money.amount_minor, qty: 1, sku: scopedProp(scope, 'sku') }]
          : [],
        fees: [],
        confidence: money ? 0.78 : 0.35,
        warnings: warnings,
      }
    }
    return null
  }

