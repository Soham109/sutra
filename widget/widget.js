  // Highest authority first. `selection` outranks everything for the *number*
  // because it is the one signal a human deliberately gave us.
  var PRIORITY = ['selection', 'shopify-cart', 'json-ld', 'shopify-meta', 'microdata', 'og', 'dom-total', 'buy-action']

  function merge(cands, doc, loc, ctx) {
    cands = cands.filter(Boolean)
    cands.sort(function (a, b) {
      return PRIORITY.indexOf(a.source) - PRIORITY.indexOf(b.source)
    })

    var out = {
      title: null,
      kind: null,
      merchant: merchantOf(doc, loc, cands),
      currency: null,
      items: [],
      fees: [],
      total_minor: null,
      confidence: 0,
      strategy: [],
      provenance: {},
      warnings: [],
      page_url: safeHref(loc),
      image: null,
      event: null,
      detected_at: new Date().toISOString(),
      version: VERSION,
    }
    if (!cands.length) {
      out.warnings.push('nothing on this page looked like a cart, a product or an order')
      return out
    }

    var used = {}
    function take(field, value, source) {
      if (out[field] !== null && out[field] !== undefined && out[field] !== '') return
      if (value === null || value === undefined || value === '') return
      out[field] = value
      out.provenance[field] = source
      used[source] = 1
    }

    // Money first: whichever candidate owns the amount also owns the currency
    // and the line items, so the three never come from different worlds.
    var moneyOwner = null
    for (var i = 0; i < cands.length; i++) {
      if (cands[i].total_minor !== null && cands[i].total_minor !== undefined) { moneyOwner = cands[i]; break }
    }
    if (moneyOwner) {
      out.total_minor = moneyOwner.total_minor
      out.kind = moneyOwner.kind || null
      out.currency = moneyOwner.currency || null
      out.provenance.total_minor = moneyOwner.source
      out.provenance.currency = moneyOwner.source
      used[moneyOwner.source] = 1
      if (moneyOwner.items && moneyOwner.items.length) {
        out.items = moneyOwner.items.map(function (it) {
          return {
            name: it.name || 'Item',
            unit_amount: it.unit_amount,
            qty: it.qty || 1,
            sku: it.sku || null,
            image: it.image || null,
          }
        })
        out.provenance.items = moneyOwner.source
      }
      if (moneyOwner.fees && moneyOwner.fees.length) {
        out.fees = moneyOwner.fees
        out.provenance.fees = moneyOwner.source
      }
    }

    for (var j = 0; j < cands.length; j++) {
      var c = cands[j]
      take('title', c.title, c.source)
      take('image', c.image, c.source)
      take('event', c.event, c.source)
      take('kind', c.kind, c.source)
      if (!out.currency && c.currency) take('currency', c.currency, c.source)
      if (c.merchantName && !out.merchant.name_from_data) {
        out.merchant.name = c.merchantName
        out.merchant.name_from_data = true
        out.provenance.merchant = c.source
        used[c.source] = 1
      }
    }
    delete out.merchant.name_from_data

    // Only surface warnings from strategies that actually shaped the answer.
    // A DOM-scrape caveat on a page whose price came from JSON-LD is noise.
    for (var y = 0; y < cands.length; y++) {
      if (!used[cands[y].source]) continue
      var ws = cands[y].warnings || []
      for (var w = 0; w < ws.length; w++) {
        if (out.warnings.indexOf(ws[w]) === -1) out.warnings.push(ws[w])
      }
    }

    // A selection or DOM read gives a total but no real line items; if a
    // richer source described the thing, keep its name on the line.
    if (out.items.length === 1 && (!out.items[0].name || out.items[0].name === 'Item' || out.items[0].name === 'Selected amount')) {
      out.items[0].name = out.title || clean(doc.title, 90) || 'Order'
    }

    if (!out.currency) {
      out.currency = ctx.weakCurrency || 'USD'
      out.provenance.currency = ctx.weakCurrencySource || 'default'
      if (!ctx.weakCurrency) out.warnings.push('no currency anywhere on the page — assumed USD')
      else out.warnings.push('currency guessed from ' + ctx.weakCurrencySource + ' (' + out.currency + ')')
    }

    // Rebuild the total from the lines when the lines are the truth.
    if (out.items.length && out.total_minor === null) {
      var sum = 0
      for (var s = 0; s < out.items.length; s++) sum += out.items[s].unit_amount * out.items[s].qty
      if (sum > 0) {
        out.total_minor = sum
        out.provenance.total_minor = out.provenance.items || 'derived'
      }
    }

    out.strategy = PRIORITY.filter(function (p) { return used[p] })
    out.confidence = score(cands, out, used)
    if (!out.title) {
      out.title = clean(doc.title) || out.merchant.name || 'This page'
      out.provenance.title = 'document.title'
    }
    return out
  }

  function score(cands, out, used) {
    var best = 0
    for (var i = 0; i < cands.length; i++) {
      if (!used[cands[i].source]) continue
      if ((cands[i].confidence || 0) > best) best = cands[i].confidence || 0
    }
    // The number is what people act on. Grade on where the *number* came from.
    var owner = out.provenance.total_minor
    var byNumber = {
      'shopify-cart': 0.97, 'json-ld': 0.9, 'shopify-meta': 0.86, 'microdata': 0.78,
      'selection': 0.75, 'og': 0.66, 'dom-total': 0.34, 'buy-action': 0.32, 'derived': 0.6,
    }
    var c = owner && byNumber[owner] !== undefined ? Math.min(best, byNumber[owner]) : best * 0.5
    if (out.total_minor === null) c = Math.min(c, 0.25)
    // Two independent sources agreeing is worth something.
    var agree = 0
    for (var k = 0; k < cands.length; k++) {
      if (cands[k].total_minor === out.total_minor && cands[k].source !== owner) agree++
    }
    if (agree) c = Math.min(0.99, c + 0.04)
    if (out.provenance.currency === 'tld' || out.provenance.currency === 'lang' || out.provenance.currency === 'default') c -= 0.08
    if (out.items.length > 1) c = Math.min(0.99, c + 0.02)
    return Math.max(0.05, Math.min(0.99, Math.round(c * 100) / 100))
  }

  function merchantOf(doc, loc, cands) {
    var host = ''
    var origin = ''
    try {
      host = String(loc.hostname || '')
      origin = String(loc.origin || (loc.protocol + '//' + loc.host) || '')
    } catch (e) {}
    var domain = host.replace(/^www\./, '')
    var name =
      meta(doc, ['og:site_name', 'application-name', 'apple-mobile-web-app-title']) ||
      brandFromDomain(domain) ||
      'Merchant'
    return { name: clean(name, 80) || 'Merchant', url: origin || (domain ? 'https://' + domain : ''), domain: domain }
  }

  var MULTI_TLD = { 'co.uk': 1, 'com.au': 1, 'co.in': 1, 'co.nz': 1, 'co.za': 1, 'com.br': 1, 'co.jp': 1, 'com.sg': 1, 'com.mx': 1, 'co.kr': 1 }

  /** shop.example.com -> "Example". en.wikipedia.org -> "Wikipedia". */
  function brandFromDomain(domain) {
    if (!domain) return null
    var parts = domain.split('.')
    if (parts.length < 2) return null
    var drop = MULTI_TLD[parts.slice(-2).join('.')] ? 2 : 1
    var label = parts[Math.max(0, parts.length - drop - 1)]
    if (!label) return null
    return label.replace(/[-_]+/g, ' ').replace(/^\w/, function (m) { return m.toUpperCase() })
  }

